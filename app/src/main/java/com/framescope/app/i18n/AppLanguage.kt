package com.framescope.app.i18n

import android.content.Context
import androidx.compose.runtime.Composable
import androidx.compose.runtime.staticCompositionLocalOf
import java.util.Locale

/** Languages currently supported by the in-app UI. */
enum class AppLanguage(val code: String, val displayName: String) {
    ENGLISH("en", "English"),
    SIMPLIFIED_CHINESE("zh-CN", "简体中文");

    companion object {
        fun fromCode(code: String?): AppLanguage? = entries.firstOrNull { it.code == code }

        fun fromSystem(): AppLanguage =
            if (Locale.getDefault().language.equals("zh", ignoreCase = true)) {
                SIMPLIFIED_CHINESE
            } else {
                ENGLISH
            }
    }
}

val LocalAppLanguage = staticCompositionLocalOf { AppLanguage.ENGLISH }

/** Snapshot used by non-composable callbacks such as Toast and update jobs. */
object AppLanguageRuntime {
    @Volatile
    var current: AppLanguage = AppLanguage.ENGLISH
}

/**
 * Small translation layer for the existing Compose UI.  Keeping the English
 * source phrase as the key makes the migration incremental and keeps the
 * English build identical to the original UI.
 */
fun translate(language: AppLanguage, text: String): String {
    if (language != AppLanguage.SIMPLIFIED_CHINESE) return text
    return ZH_TRANSLATIONS[text] ?: text
}

fun trStatic(text: String): String = translate(AppLanguageRuntime.current, text)

@Composable
fun tr(text: String): String = translate(LocalAppLanguage.current, text)

fun loadInitialLanguage(context: Context): AppLanguage {
    val stored = context.getSharedPreferences("framescope_settings", Context.MODE_PRIVATE)
        .getString("app_language", null)
    return AppLanguage.fromCode(stored) ?: AppLanguage.fromSystem()
}

